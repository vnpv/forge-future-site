export const REF_RE = /^[a-z0-9]{1,16}$/;

export function cleanRef(raw: string | null | undefined): string {
  const v = (raw ?? "").toLowerCase().replace(/[^a-z0-9]/g, "").slice(0, 16);
  return REF_RE.test(v) ? v : "";
}

/**
 * Посилання на бота. Payload: ff_q-<ref|0>-<профіль><віки><дім><пробували><страх>
 * (символи A-Za-z0-9_- , до 64). Бот @ivanpervoy_bot розбирає його в forge_bot/handlers.py.
 */
export function botLink(ref: string, answers: number[]): string {
  const list = isJuniorAge(answers[0]) ? juniorProfiles : profiles;
  const profile = list[answers[1]]?.id ?? list[0].id;
  const code = profile + answers.map((a) => String(a)).join("");
  return `https://t.me/${TELEGRAM_BOT_USERNAME}?start=ff_q-${ref || "0"}-${code}`;
}

